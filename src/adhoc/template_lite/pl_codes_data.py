def get_leafs(code:str)->List[str]:

    l = get_logger()

    def _rec_fn(_code)->List[str]:
        l.debug(f'<< rec_fn enter: {_code} >>')
        rs = []
        chlds = _find_children(_code)

        if len(chlds) == 0:
            return [_code]

        for x in chlds:
            rs.extend(_rec_fn(x))

        l.debug(f'<< rec_fn exit: {_code}, res:{rs} >>')
        return rs

    return _rec_fn(code)




