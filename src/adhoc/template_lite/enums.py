"""
Enum классы для строковых констант модуля template_lite.

Этот модуль содержит перечисления, используемые для типизации полей
упрощённого («lite») шаблона сценария обхода данных для факторного анализа.

Единственное поле JSON-сценария, значения которого образуют конечное
множество из 2–5 элементов — это ``role`` узла. Все четыре значения поля
``role`` упакованы в enum :class:`NodeRole`.
"""

from enum import Enum


class NodeRole(str, Enum):
    """
    Роль узла в упрощённом шаблоне сценария обхода (template lite).

    Роль определяет семантику узла в дереве сценария и то, как этот узел
    впоследствии отображается на полноценные метаданные факторного анализа:

    - :attr:`PODSTATYA` — «подстатья». Суммируемый компонент показателя
      (отдельная статья дохода/расхода). Может иметь собственных потомков:
      вложенные подстатьи, аналитические разрезы либо пару «тариф + база».
      Аналог суммируемого компонента в полной иерархии метрик.
    - :attr:`RAZREZ` — «разрез». Аналитический разрез/срез данных
      (например, «ТБ/ГОСБ», «Блок/Подблок», «Продукт ЕК»). Узел этой роли
      описывает измерение, по которому выполняется детализация (drill-down).
    - :attr:`TARIF` — «тариф». Компонент-множитель (ставка/процент)
      мультипликативного показателя. Всегда является листовым потомком
      подстатьи и идёт в паре с :attr:`BAZA`. Аналог ``rate`` в
      :class:`~libfa2.hier_metadata.ComponentMultiPartType`.
    - :attr:`BAZA` — «база». Объёмный показатель, на который умножается
      тариф. Всегда является листовым потомком подстатьи и идёт в паре с
      :attr:`TARIF`. Аналог ``base`` в
      :class:`~libfa2.hier_metadata.ComponentMultiPartType`.
    """

    #: Подстатья — суммируемый компонент показателя
    PODSTATYA = "podstatya"

    #: Разрез — аналитический разрез/срез данных
    RAZREZ = "razrez"

    #: Тариф — компонент-множитель (ставка) мультипликативного показателя
    TARIF = "tarif"

    #: База — объёмный показатель мультипликативного показателя
    BAZA = "baza"
